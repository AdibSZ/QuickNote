import 'package:flutter/material.dart';

/// Smooth fluid entrance animation for note blocks, giving tactile, lively feedback on block creation.
class AnimatedBlockEntry extends StatefulWidget {
  final Widget child;

  const AnimatedBlockEntry({super.key, required this.child});

  @override
  State<AnimatedBlockEntry> createState() => _AnimatedBlockEntryState();
}

class _AnimatedBlockEntryState extends State<AnimatedBlockEntry>
    with SingleTickerProviderStateMixin {
  late AnimationController _controller;
  late Animation<double> _fade;
  late Animation<Offset> _slide;

  @override
  void initState() {
    super.initState();
    _controller = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 240),
    );
    _fade = CurvedAnimation(parent: _controller, curve: Curves.easeOut);
    _slide = Tween<Offset>(
      begin: const Offset(0, 0.08),
      end: Offset.zero,
    ).animate(CurvedAnimation(parent: _controller, curve: Curves.easeOutCubic));

    _controller.forward();
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return FadeTransition(
      opacity: _fade,
      child: SlideTransition(
        position: _slide,
        child: widget.child,
      ),
    );
  }
}
